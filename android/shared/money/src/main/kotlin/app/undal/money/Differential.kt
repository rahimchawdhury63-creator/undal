package app.undal.money

import java.io.File

/**
 * Answers the shared 110 000 vectors in Kotlin, for `scripts/money/differential.py`.
 *
 * The differential is only real if all three languages answer the *same* file, so this
 * reads the vectors the TypeScript generator wrote and emits the same five-field rows the
 * Python side emits: rate, floored total, delta, the grouped amount, the grouped rate.
 * It is a `main` rather than a JUnit test because a test can only assert against values
 * compiled into it, and the point is to assert against values compiled into *another*
 * language's artefact.
 */
object Differential {

    private val AMOUNT = Regex("\"amount\"\\s*:\\s*(-?\\d+)")
    private val RATE = Regex("\"rateBps\"\\s*:\\s*(-?\\d+)")

    /**
     * Read the vectors, answer them, write the JSON array.
     *
     * The JSON is parsed with two regexes on purpose: the file is a flat array of objects
     * with two integer fields, generated by our own script, and a serialisation plugin
     * would be a second dependency in the module whose whole job is to have none.
     */
    @JvmStatic
    fun main(args: Array<String>) {
        val vectorsPath = args.getOrElse(0) { ".artifacts/money/vectors.json" }
        val outputPath = args.getOrElse(1) { ".artifacts/money/kotlin.json" }

        val source = File(vectorsPath)
        check(source.isFile) { "missing $vectorsPath: run the TypeScript generator first" }
        val text = source.readText()
        val amounts = AMOUNT.findAll(text).map { it.groupValues[1].toLong() }.toList()
        val rates = RATE.findAll(text).map { it.groupValues[1].toLong() }.toList()
        check(amounts.size == rates.size && amounts.isNotEmpty()) {
            "vectors are malformed: ${amounts.size} amounts, ${rates.size} rates"
        }

        val rows = amounts.indices.map { index ->
            val amount = amounts[index]
            val rateBps = rates[index]
            val computed = Money.applyRate(amount, rateBps)
            val floored = Money.floorToTaka(amount)
            buildString {
                append('[')
                append(computed).append(',')
                append(floored.first).append(',')
                append(floored.second).append(',')
                append('"').append(Money.groupBdt(amount).amount).append("\",")
                append('"').append(Money.groupBdt(computed).withSymbol).append('"')
                append(']')
            }
        }

        val output = File(outputPath)
        output.parentFile?.mkdirs()
        output.writeText(rows.joinToString(separator = ",", prefix = "[", postfix = "]"))
        println("kotlin: ${rows.size} answers written to $outputPath")
    }
}
