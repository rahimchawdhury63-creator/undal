from __future__ import annotations

import json
import unittest
from dataclasses import asdict
from pathlib import Path

from fare.constants import BICYCLE, LAUNCH_PRICING, MOTORBIKE
from fare.engine import compute_fare
from fare.inputs import FareInput

VECTORS = json.loads((Path(__file__).resolve().parent / "vectors" / "fare_vectors.json").read_text())
PRICING = {MOTORBIKE: LAUNCH_PRICING[MOTORBIKE], BICYCLE: LAUNCH_PRICING[BICYCLE]}


def build(raw) -> FareInput:
    return FareInput(
        pricing=PRICING[raw["vehicle"]],
        routed_distance_m=raw["routed_distance_m"],
        traffic_delay_s=raw["traffic_delay_s"],
        riders=raw["riders"],
        orders=raw["orders"],
        weather=raw["weather"],
        weather_confidence=raw["weather_confidence"],
        item_subtotal_paisa=raw["item_subtotal_paisa"],
        tip_paisa=raw["tip_paisa"],
        fulfilment=raw["fulfilment"],
        batch_position=raw["batch_position"],
        batch_marginal_distance_m=raw["batch_marginal_distance_m"],
    )


class TestVectorOneByHand(unittest.TestCase):
    def test_the_documented_figures(self):
        quote = compute_fare(build(VECTORS["vectors"][0]["input"]))
        b = quote.breakdown
        self.assertEqual(quote.surge_bps, 10_000)
        self.assertEqual(b.core.surged_base_paisa, 4_000)
        self.assertEqual(b.core.distance_paisa, 2_520)
        self.assertEqual(b.core.traffic_paisa, 0)
        self.assertEqual(b.core.total_paisa, 6_520)
        self.assertEqual(b.delivery_margin_paisa, 522)
        self.assertEqual(b.delivery_fee_paisa, 7_042)
        self.assertEqual(b.small_order.total_paisa, 2_500)
        self.assertEqual(b.small_order.rider_paisa, 500)
        self.assertEqual(b.small_order.vendor_paisa, 500)
        self.assertEqual(b.small_order.platform_paisa, 1_500)
        self.assertEqual(b.rider_bonus_paisa, 1_350)
        self.assertEqual(b.commission_paisa, 6_750)
        self.assertEqual(b.taxable_base_paisa, 8_772)
        self.assertEqual(b.tax_paisa, 439)
        # total = pre-round + delta, and delta is negative: pre-round is total − delta.
        self.assertEqual(b.customer_total_paisa - b.rounding_delta_paisa, 54_981)
        self.assertEqual(b.customer_total_paisa, 54_900)
        self.assertEqual(b.rounding_delta_paisa, -81)
        self.assertEqual(b.vendor_payout_paisa, 37_400)
        self.assertEqual(b.rider_payout_paisa, 8_370)
        self.assertEqual(b.platform_rounding_expense_paisa, 81)


class TestEveryVector(unittest.TestCase):
    def test_all_forty_reproduce_and_close(self):
        self.assertEqual(len(VECTORS["vectors"]), 40)
        for entry in VECTORS["vectors"]:
            quote = compute_fare(build(entry["input"]))
            self.assertEqual(quote.surge_bps, entry["surge_bps"], entry["id"])
            actual = asdict(quote.breakdown)
            for key, expected in entry["expected"].items():
                self.assertEqual(actual[key], expected, f"vector {entry['id']} {key}")

    def test_every_vector_closes_over_its_own_terms(self):
        for entry in VECTORS["vectors"]:
            b = compute_fare(build(entry["input"])).breakdown
            total = (
                b.vendor_payout_paisa
                + b.rider_payout_paisa
                + b.platform_commission_paisa
                + b.platform_small_order_paisa
                + b.platform_delivery_net_paisa
                + b.platform_tax_payable_paisa
                - b.platform_rounding_expense_paisa
            )
            self.assertEqual(total, b.customer_total_paisa, entry["id"])

    def test_the_weather_premium_never_reaches_the_customer(self):
        clear = compute_fare(build({**VECTORS["vectors"][0]["input"]})).breakdown
        storm_input = {**VECTORS["vectors"][0]["input"], "weather": "STORM"}
        storm = compute_fare(build(storm_input)).breakdown
        self.assertEqual(storm.delivery_fee_paisa, clear.delivery_fee_paisa)
        self.assertGreater(storm.rider_payout_paisa, clear.rider_payout_paisa)
        self.assertGreater(storm.platform_weather_expense_paisa, 0)


if __name__ == "__main__":
    unittest.main()
